export function generateTemplateLetters(answers) {
  const a = withDefaults(answers);
  return DAY_LETTERS.map((build, idx) => {
    const day = idx + 1;
    const { title, body, question, action } = build(a);
    return {
      day,
      title: `Day${day}｜${title}`,
      body,
      question: question || null,
      action: action || null,
      source: "template",
    };
  });
}

export function buildEmailPreview(letter, name) {
  const subject = `【Day${letter.day}】1年後のあなたから手紙が届きました`;
  const excerpt = letter.body.split("\n").find((l) => l.trim().length > 0) || "";
  return { subject, name, title: letter.title, excerpt };
}
