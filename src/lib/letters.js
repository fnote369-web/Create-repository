// Template-mode letter generator: builds 30 distinct letters ("Day1"-"Day30")
// from the user's onboarding answers, without calling any external AI API.
// This is the free/default mode, and also the fallback used when AI
// generation (see Letters.gs on the backend) fails or is disabled.
//
// Voice rules for "1年後の少し成熟した私" (see gas-backend/Letters.gs for
// the mirrored server-side copy — keep both in sync manually):
//   - Not a teacher, not a therapist, not a "success story". Someone who
//     is simply one year further along, living an ordinary life.
//   - Full emotional range: excited, tired, annoyed, content, bored,
//     nothing-happened days, laughing-with-someone days. Never uniformly
//     calm/wise.
//   - Doesn't moralize or ask a reflective question every day. Most
//     letters have no `question`/`action` at all (see DAY_LETTERS below —
//     only a minority set them).
//   - Doesn't report achievements as a success story ("収入がこうなり
//     ました!" is banned). Answers are dissolved into a lived scene, not
//     echoed back literally ("京都に行きたい" -> already standing in a
//     small Kyoto inn, not "行けました!").
//   - Varies opening style, length, and how it signs off — deliberately,
//     so consecutive letters don't read as templated, while still reading
//     as one continuous person across 30 days.
//   - Day 30 does not "graduate" the reader with a tidy lesson.

